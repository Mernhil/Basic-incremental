import { createHash } from 'node:crypto';

/** The home-screen app's identity (iPhone: Share > Add to Home Screen). Colours are the game's table. */
export const THEME_COLOR = '#17131f';

export const ICON_SIZES = [180, 192, 512] as const;

export function webManifest(version: string) {
  return {
    name: 'Basic Incremental',
    short_name: 'Basic Inc.',
    description: `Basic Incremental ${version}`,
    start_url: './',
    scope: './',
    display: 'fullscreen',
    display_override: ['fullscreen', 'standalone'],
    orientation: 'landscape',
    background_color: THEME_COLOR,
    theme_color: THEME_COLOR,
    icons: [
      { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
      { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
    ],
  };
}

/** One cache per build: the version and a hash of the file list, so a new build is a new cache. */
export function webCacheName(version: string, files: readonly string[]): string {
  const hash = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 10);
  return `bi-${version}-${hash}`;
}

/**
 * The service worker: caches every built file at install, so the game starts with no network, and
 * answers from the cache first. It does not skip waiting: a new build installs beside the old one
 * and takes over on the next launch, when the app has been closed (no mixed old and new files in
 * one session). Old caches go when the new worker becomes active.
 */
export function serviceWorkerSource(cacheName: string, files: readonly string[]): string {
  return `// generated by vite.web.config.ts, do not edit
const CACHE = ${JSON.stringify(cacheName)};
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith('bi-') && k !== CACHE).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(request).catch(() =>
          request.mode === 'navigate'
            ? caches.match(new URL('index.html', self.registration.scope).href)
            : Response.error(),
        ),
    ),
  );
});
`;
}
